/**
 * Copies ABIs from the Foundry build (contracts/out) into shared/src/abis/generated.ts as `as const`
 * literals, so viem infers types for the web app and the scripts. Re-run after `forge build`.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const OUT = join(import.meta.dirname, "..", "contracts", "out")
const CONTRACTS = [
  "RegXDvP",
  "TINR",
  "InvestorCapModule",
  "ClaimTopicsRegistry",
  "TrustedIssuersRegistry",
  "IdentityRegistryStorage",
  "IdentityRegistry",
  "ModularCompliance",
  "Identity",
  "ClaimIssuer",
]

let src = "// AUTO-GENERATED by scripts/export-abis.ts. Do not edit.\n\n"
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(OUT, `${name}.sol`, `${name}.json`), "utf8"))
  src += `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(artifact.abi)} as const\n\n`
}
writeFileSync(join(import.meta.dirname, "..", "shared", "src", "abis", "generated.ts"), src)

// Server-only: bytecode needed by the web app's demo KYC desk (ONCHAINID deployment)
const identity = JSON.parse(readFileSync(join(OUT, "Identity.sol", "Identity.json"), "utf8"))
writeFileSync(
  join(import.meta.dirname, "..", "shared", "src", "abis", "bytecode.ts"),
  `// AUTO-GENERATED by scripts/export-abis.ts. Server-side only.\nexport const identityBytecode = "${identity.bytecode.object}" as const\n`,
)
console.log(`exported ${CONTRACTS.length} ABIs`)
